def C(cid, title, category, collar, smin, smax, note, desc, skills, paths, quals, tags, work, growth):
    """India role - salaries in INR/month."""
    return {"id": cid, "title": title, "category": category, "region": "IN", "description": desc,
            "salary_range": {"min": smin, "max": smax, "currency": "INR/month", "note": note},
            "growth_outlook": growth, "work_style": work,
            "required_skills": [{"skill": s, "level": l} for s, l in skills],
            "entry_paths": paths, "qualifications": quals, "tags": tags, "collar": collar}


def U(cid, title, category, collar, smin, smax, note, desc, skills, paths, quals, tags, work, growth):
    """US role - salaries in USD/year."""
