def _norm(s):
    """Collapse dash variants and whitespace so an ASCII source file can still
    match canonical skill names that contain en/em dashes."""
    out = s.replace(u"\u2014", "-").replace(u"\u2013", "-").replace(u"\u2212", "-")
    return " ".join(out.lower().split())


def canonicalise_skill_names():
    """Rewrite new-career skill names onto the exact spelling already in
    skills.json wherever only the dash style differs - otherwise we would add a
    near-duplicate skill that splits search results."""
    with open(SKILLS, encoding="utf-8") as f:
        known = json.load(f)["all_skills"]
    exact = {s for s in known}
    by_norm = {}
    for s in known:
        by_norm.setdefault(_norm(s), s)

    fixed = 0
    for c in NEW:
        for r in c["required_skills"]:
            if r["skill"] in exact:
                continue
            canon = by_norm.get(_norm(r["skill"]))
            if canon and canon != r["skill"]:
                print("CANONICALISE: %r -> %r (%s)" % (r["skill"], canon, c["id"]))
                r["skill"] = canon
                fixed += 1
    print("Canonicalised %d skill references." % fixed)


def update_careers():
    with open(CAREERS, encoding="utf-8") as f:
        text = f.read()

    existing = json.loads(text)
    ids = {c["id"] for c in existing}
    titles = {(c["title"].strip().lower(), c.get("region", "IN")) for c in existing}

    to_add = []
    for c in NEW:
        key = (c["title"].strip().lower(), c["region"])
        if c["id"] in ids or key in titles:
            print("SKIP (duplicate):", c["id"], "|", c["title"])
            continue
        ids.add(c["id"])
        titles.add(key)
        to_add.append(c)

    if to_add:
        idx = text.rstrip().rfind("]")
        head = text.rstrip()[:idx].rstrip()
        chunks = ["\n".join("  " + ln for ln in json.dumps(c, ensure_ascii=False, indent=2).splitlines())
                  for c in to_add]
        text = head + ",\n" + ",\n".join(chunks) + "\n]\n"

    parsed = json.loads(text)
    assert len(parsed) == len(existing) + len(to_add), "career count mismatch"
    with open(CAREERS, "w", encoding="utf-8") as f:
        f.write(text)
    print("Added %d careers. Total now %d." % (len(to_add), len(parsed)))
    return parsed


def update_skills(careers):
    with open(SKILLS, encoding="utf-8") as f:
        data = json.load(f)

    added = 0
    for cat, skills in NEW_SKILLS.items():
        bucket = data["categories"].setdefault(cat, [])
        have = {s.lower() for s in bucket}
        for s in skills:
            if s.lower() not in have:
                bucket.append(s)
                have.add(s.lower())
                added += 1

    all_lower = {s.lower() for s in data["all_skills"]}
    for bucket in data["categories"].values():
        for s in bucket:
            if s.lower() not in all_lower:
                data["all_skills"].append(s)
                all_lower.add(s.lower())

    data["all_skills"].sort(key=lambda s: s.lower())
    with open(SKILLS, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("Added %d skills. Categories: %d, all_skills: %d."
          % (added, len(data["categories"]), len(data["all_skills"])))

    # Every skill referenced by a career must be selectable in the UI.
    missing = sorted({r["skill"] for c in careers for r in c.get("required_skills", [])
                      if r["skill"].lower() not in all_lower})
    if missing:
        print("WARNING - career skills not in all_skills (%d):" % len(missing))
        for m in missing:
            print("   ", m)
    else:
        print("All career skills resolve to skills.json.")
    return all_lower


def update_synonyms(all_lower):
    with open(SYNONYMS, encoding="utf-8") as f:
        text = f.read()

    entries = dict(re.findall(r'^  "([^"]+)": (\[[^\]]*\]),$', text, re.M))
    added = 0
    for word, skills in NEW_SYNONYMS.items():
        live = [s for s in skills if s.lower() in all_lower]
        if not live:
            print("SKIP synonym (no live skills):", word)
            continue
        if word in entries:
            continue
        entries[word] = json.dumps(live, ensure_ascii=False)
        added += 1

    head = text.split("const SKILL_SYNONYMS = {", 1)[0]
    body = "".join('  "%s": %s,\n' % (w, entries[w]) for w in sorted(entries))
    with open(SYNONYMS, "w", encoding="utf-8") as f:
        f.write(head + "const SKILL_SYNONYMS = {\n" + body + "};\n")
    print("Added %d search words. Total now %d." % (added, len(entries)))


def main():
    canonicalise_skill_names()
    careers = update_careers()
    all_lower = update_skills(careers)
    update_synonyms(all_lower)


if __name__ == "__main__":
    main()
